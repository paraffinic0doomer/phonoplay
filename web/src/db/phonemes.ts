/**
 * What the learner model currently believes about one sound.
 *
 * Reads the mode from settings so callers do not have to carry it, and so
 * switching to Accessibility Mode changes every judgement at once rather than
 * wherever someone remembered to check.
 */
export async function evaluate(phoneme: Phoneme): Promise<{
  profile: PhonemeProfile
  policy: LearnerPolicy
  mastery: MasteryVerdict
  stage: StageVerdict
}> {
  const [profile, mode] = await Promise.all([getProfile(phoneme), getLearningMode()])
  const policy = policyFor(mode)
  return {
    profile,
    policy,
    mastery: assessMastery(profile, policy),
    stage: assessStage(profile, policy),
  }
}

/**
 * Advance the stage if the evidence supports it, and report either way.
 *
 * Nothing here can move a learner backwards. A poor run leaves the stage
 * where it is, which is a pause rather than a demotion — being sent back a
 * rung for a bad day is punitive, and CLAUDE.md rules out punitive failure.
 */
export async function advanceIfReady(phoneme: Phoneme): Promise<{
  profile: PhonemeProfile
  advanced: boolean
  verdict: StageVerdict
}> {
  const { profile, stage } = await evaluate(phoneme)
  if (!stage.advance) return { profile, advanced: false, verdict: stage }

  const updated = await setStage(phoneme, stage.stage)
  return { profile: updated, advanced: true, verdict: stage }
}

/** Every sound the model currently considers mastered, under the active mode. */
export async function getMastered(): Promise<Phoneme[]> {
  const mode = await getLearningMode()
  const policy = policyFor(mode)
  const profiles = await getAllProfiles()
  return profiles
    .filter((profile) => assessMastery(profile, policy).mastered)
    .map((profile) => profile.phoneme)
}

/**
 * Move a phoneme to a different stage.
 *
 * `repetitionCount` resets, because it counts attempts *at the current
 * stage* — which is what accessibility mode's "more repetition before moving
 * on" is measured against.
 */
export async function setStage(
  phoneme: Phoneme,
  stage: SkillType,
): Promise<PhonemeProfile> {
  const profile = await getProfile(phoneme)
  if (!STAGE_ORDER.includes(stage)) {
    throw new Error(`Unknown stage "${stage}".`)
  }
  const updated: PhonemeProfile = {
    ...profile,
    currentStage: stage,
    repetitionCount: stage === profile.currentStage ? profile.repetitionCount : 0,
    updatedAt: now(),
  }
  await db.phonemeProfiles.put(updated)
  return updated
}

/** Recompute contrast accuracy for one phoneme from its contrast attempts. */
export async function setContrastAccuracy(
  phoneme: Phoneme,
  accuracy: number | null,
): Promise<PhonemeProfile> {
  const profile = await getProfile(phoneme)
  const updated: PhonemeProfile = {
    ...profile,
    contrastAccuracy: accuracy === null ? null : round(clamp01(accuracy)),
    updatedAt: now(),
  }
  await db.phonemeProfiles.put(updated)
  return updated
}

function clamp01(value: number): number {
  return Math.max(0, Math.min(1, value))
}

function round(value: number): number {
  return Math.round(value * 1e4) / 1e4
}
