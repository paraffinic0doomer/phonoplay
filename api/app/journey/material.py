def _first_word(text: str) -> str:
    cleaned = "".join(c for c in text.lower() if c.isalpha() or c.isspace()).strip()
    return cleaned.split(" ")[0] if cleaned else ""


def starts_with_target(text: str, sound: str) -> bool:
    """
    Does the first word actually begin with the target sound?

    Spelling-based and deliberately strict. This is the guard that stops
    generated material from silently breaking the measurement: the acoustic
    stage looks for the target at the start of the utterance, so material
    whose first word does not begin with it would be scored against
    something that is not there.
    """
    word = _first_word(text)
    if not word:
        return False
    if sound == "th" and (word in _VOICED_TH or word.startswith(_VOICED_TH_PREFIX)):
        return False
    # `text` is already a bare sound at the isolated stage.
    if word == sound or (sound == "th" and word.startswith("th")):
        return True
    if any(word.startswith(bad) for bad in _ONSET_EXCLUSIONS.get(sound, ())):
        return False
    return any(word.startswith(good) for good in _ONSET_SPELLINGS.get(sound, ()))


def fallback(
    sound: str, stage_index: int, *, avoid: str | None = None, native: str = DEFAULT_NATIVE
) -> Material:
    """
    Deterministic material. Always available, always valid.

    The bank itself is not translated or varied by first language. The words
    that isolate an English /s/ are the same words whoever is practising, and
    producing a separate bank per language would mean maintaining several
    sets of English words with no reason for them to differ. What the first
    language changes is the *bridge* shown alongside (see `app/languages.py`)
    and the context given to the generator below.
    """
    current = stage_at(stage_index)
    options = _BANK[sound][current.key]
    # `avoid` implements "hold with varied material": pick something the
    # learner did not just do, when there is anything else to pick.
    choices = [o for o in options if o.text != avoid] or options
    return _wrap(sound, current, random.choice(choices), "fallback", native)


def _wrap(
    sound: str, current: Stage, item: StageMaterial, source: str, native: str = DEFAULT_NATIVE
) -> Material:
    return Material(
        sound=sound,
        stage=current.index,
        stage_key=current.key,
        item=item,
        source=source,
        position="onset",
        first_occurrence_only=current.index >= 5,
        native_language=normalise_native(native),
        target_language="en",
    )


_SYSTEM = (
    "You write very short pronunciation practice material for a children's "
    "speech-learning app. You never assess, score, rate or diagnose anything: "
    "a separate acoustic system measures the recording and owns every "
    "judgement about performance. Never mention disorders, diagnosis, "
    "therapy or clinical terms. "
    # The learner's first language is given as context so that examples can be
    # familiar. It is not licence to explain their pronunciation with it.
    "When you are told a learner's first language, use it only to choose "
    "words and examples that will be familiar. Never say or imply that their "
    "first language causes, explains, or predicts any pronunciation pattern, "
    "and never describe any language as lacking, missing, or deficient in a "
    "sound. Reply with JSON only."
)


def _user_prompt(
    sound: str, current: Stage, avoid: str | None, native: str = DEFAULT_NATIVE
) -> str:
    shape = {
        "isolated": "the single sound held on its own",
        "syllable": "the sound joined to one vowel, as a nonsense syllable",
        "word": "one short, common, single-syllable word",
        "word_complex": "one common word of two or three syllables",
        "phrase": "a two or three word phrase",
        "sentence": "one short sentence of six to ten words",
        "conversation": "an unfinished sentence opener of three to five words for "
        "the learner to complete in their own words",
    }[current.material]

    rules = [
        f"Target sound: /{sound}/.",
        f"Produce {shape}.",
        "The FIRST word must begin with the target sound.",
        "Use real English words a seven-year-old knows.",
        "cue: one sentence about where the tongue or lips go. No praise, no assessment.",
        "contrast: a minimal-pair word differing only in the target sound, or null.",
        'display: only for a bare sound, e.g. "sssss". Otherwise null.',
        "Return exactly: {\"text\": str, \"display\": str|null, "
        '"contrast": str|null, "cue": str}',
        "Do not include any other field. Do not include any number, score, "
        "rating or percentage anywhere in the response.",
    ]
    resolved = normalise_native(native)
    if resolved != "en":
        # Context, deliberately narrow: familiarity of examples, nothing else.
        # The target is always English — the sound being measured is an
        # English one — and saying so keeps the model from drifting into
        # generating practice material in the learner's first language.
        rules.append(
            f"The learner's first language is {language(resolved).name} and "
            "they are learning English. The word must still be an English "
            "word. Where a natural choice exists, prefer everyday words that "
            "would be familiar to a learner in that cultural context. Do not "
            "explain their pronunciation by reference to their first language."
        )
    if avoid:
        rules.append(f'Do not use "{avoid}" — the learner has just practised it.')
    return "\n".join(rules)


def _parse(content: str) -> StageMaterial:
    text = content.strip().removeprefix("```json").removeprefix("```").removesuffix("```")
    payload = json.loads(text)
    if not isinstance(payload, dict):
        raise ValueError("generator returned a non-object")
    # Validation, not sanitisation. A response carrying an unexpected field
    # is rejected rather than cleaned up, so the guard cannot be defeated by
    # a field name nobody thought of.
    return StageMaterial.model_validate(payload)


async def generate(
    sound: str,
    stage_index: int,
    settings: Settings,
    *,
    avoid: str | None = None,
    native: str = DEFAULT_NATIVE,
    client: httpx.AsyncClient | None = None,
) -> Material:
    """
    Ask Groq for material, and fall back to the bank on any problem at all.

    Never raises. A failed generation is not an error the learner should see —
    it is a reason to use a hand-written exercise that is just as good.
    """
    current = stage_at(stage_index)

    # The isolated stage has exactly one correct answer and nothing to vary.
    # Spending an API call to be told to hold an /s/ would be waste.
    if current.material == "isolated":
        return fallback(sound, stage_index, avoid=avoid, native=native)

    keys = settings.groq_api_key_pool
    if not keys:
        return fallback(sound, stage_index, avoid=avoid, native=native)

    payload: dict[str, Any] = {
        "model": settings.groq_chat_model,
        "temperature": 0.7,
        # 1200, not the ~300 the output actually needs. Reasoning models on
        # Groq (the gpt-oss family) spend tokens thinking before they emit
        # anything, and that budget is shared with the response. At 300 the
        # longer stages returned HTTP 400 json_validate_failed with an empty
        # `failed_generation` — the model had produced no JSON at all before
        # running out. The wasted headroom costs nothing when unused.
        "max_tokens": 1200,
        "response_format": {"type": "json_object"},
        "messages": [
            {"role": "system", "content": _SYSTEM},
            {"role": "user", "content": _user_prompt(sound, current, avoid, native)},
        ],
    }
    url = f"{settings.groq_base_url.rstrip('/')}/chat/completions"

    owned = client is None
    http = client or httpx.AsyncClient(timeout=settings.llm_timeout_s)
    try:
        # One attempt per key, no retry within a key: the bank is right there,
        # and a learner waiting on a second timeout is worse than a
        # hand-written word.
        for key in keys:
            try:
                response = await http.post(
                    url, headers={"Authorization": f"Bearer {key}"}, json=payload
                )
                response.raise_for_status()
                item = _parse(response.json()["choices"][0]["message"]["content"])
            except (httpx.HTTPError, KeyError, IndexError, TypeError, ValueError, ValidationError) as exc:
                log.info("material generation failed on one key: %s", type(exc).__name__)
                continue

            if not starts_with_target(item.text, sound):
                log.info(
                    "generated %r does not start with /%s/ — using the bank", item.text, sound
                )
                continue

            return _wrap(sound, current, item, "llm", native)
    finally:
        if owned:
            await http.aclose()

    return fallback(sound, stage_index, avoid=avoid, native=native)
