"""
Practice material for a stage — generated by Groq, bounded by code.

The division of labour here is the point of the whole feature:

    the language model writes the exercise
    the microphone decides whether it was passed

Groq is asked for words, phrases and sentences suited to the learner's
current stage. It is never asked how well anything was pronounced, it never
sees a recording, and nothing it returns can reach the progression policy.
Three separate mechanisms enforce that rather than one:

  1. `StageMaterial` sets `extra="forbid"`, so a response carrying a score,
     a rating, a percentage or any other unexpected field fails validation
     outright instead of being quietly ignored.
  2. Every field is a string. There is no numeric field for a model to fill
     in even if it wanted to.
  3. `generate()` returns material only. The caller measures the recording
     separately and never passes this object to `policy.decide()`.

Beyond that, generated material is *verified before use*: the target sound
has to actually be at the start of the first word, checked against the
spelling in code. A model that returns "banana" for an /s/ stage is rejected
and the deterministic bank is used instead. Plausible-looking material that
does not contain the sound being practised would corrupt the measurement
downstream, which is a subtler failure than a wrong score and a worse one.

**The fallback bank is not a degraded mode.** It is hand-written, covers
every stage of every sound, and is what runs with no API key, no network, a
timeout, or a rejected response. The demo never depends on a network call.
"""

