#: Every journey item's target sound is word-initial, and `Material.position`
#: is always "onset" as a result. Practising a sound in the middle or at the
#: end of a word is genuinely valuable — "yellow" for /l/, "bath" for /th/ —
#: but the segmenter locates a medial approximant far less reliably than an
#: initial one, and a journey that advanced people on an unreliable
#: measurement would be worse than one that covers less ground. The older
#: /api/attempts prompt bank does carry coda and medial positions; the
#: journey will follow once alignment lands (ARCHITECTURE.md §3).
#:
#: Spelling prefixes that reliably begin with each target sound. Used to
#: verify generated material. Conservative on purpose — "city" does start
#: with /s/, but accepting soft-c would also accept "chair", and a missed
#: good word costs nothing while a wrong one corrupts a measurement.
_ONSET_SPELLINGS: dict[str, tuple[str, ...]] = {
    "s": ("s",),
    "th": ("th",),
    "r": ("r", "wr"),
    "l": ("l",),
}
#: Prefixes that look right but are a different sound entirely.
_ONSET_EXCLUSIONS: dict[str, tuple[str, ...]] = {
    "s": ("sh",),
    # See _VOICED_TH below: "th" cannot be excluded by prefix, because the
    # voiced and voiceless spellings are the same.
    "th": (),
    "r": (),
    "l": (),
}

#: Word-initial voiced TH. A closed class, and every one of them is a trap.
#:
#: English spells /theta/ and /eth/ identically. The reference corpus for "th"
#: is entirely voiceless - theme, thick, thin, thing, think, thumb - so a
#: prompt beginning "the" or "this" would be measured against a profile for a
#: different sound, and a learner producing it perfectly would be marked down
#: for it. Observed: a generated /th/ phrase came back as "the thick thrum"
#: and a sentence as "This thing is theirs", both of which begin voiced.
#:
#: Matched whole-word, not by prefix, because "theme" and "therapy" are
#: voiceless and would be caught by any prefix that catches "the".
_VOICED_TH: frozenset[str] = frozenset(
    {
        "the", "this", "that", "these", "those",
        "they", "them", "their", "theirs", "themselves",
        "then", "than", "though", "thus", "thence",
        "thee", "thy", "thine", "thou", "tho",
    }
)

#: "there", "therefore", "thereby"... all voiced. No voiceless word starts
#: "there" - "therapy" and "therapeutic" start "thera".
_VOICED_TH_PREFIX = "there"


class StageMaterial(BaseModel):
    """
    One thing to practise. Strings only, and no field a score could occupy.

    `extra="forbid"` is load-bearing: it is what turns "the model added a
    `score` field" from a silent no-op into a validation error.
    """

    model_config = ConfigDict(extra="forbid")

    #: What the learner says. Exactly what is measured.
    text: str = Field(min_length=1, max_length=160)
    #: A friendlier rendering for stages where `text` is not a word —
    #: "ssss" for a held /s/, say. Display only.
    display: str | None = Field(default=None, max_length=40)
    #: A minimal-pair counterpart, shown for contrast. Never practised, and
    #: never measured.
    contrast: str | None = Field(default=None, max_length=40)
    #: One short articulation tip.
    cue: str = Field(min_length=1, max_length=200)


class Material(BaseModel):
    """What the endpoint returns."""

    sound: str
    stage: int
    stage_key: str
    item: StageMaterial
    #: "llm" or "fallback". Always shown in the UI — a learner should be able
    #: to see where their exercise came from.
    source: str
    #: Where in the utterance the target sound is measured.
    position: str = "onset"
    #: True at stages 5-7, where only the first occurrence is assessed.
    first_occurrence_only: bool = False
    #: The learner's first language at the time this was generated, and the
    #: language being practised. Reported so the UI can show what the
    #: material was personalized for — and so it is visible that the target
    #: is always English.
    native_language: str = DEFAULT_NATIVE
    target_language: str = "en"


